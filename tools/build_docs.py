def set_font(run, name="Times New Roman", size=14, bold=False, italic=False,
             color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), name)


def setup_page(doc, font="Times New Roman", size=14, spacing=1.5,
               first_line=1.25, space_after=0):
    for section in doc.sections:
        section.top_margin = Cm(2)
        section.bottom_margin = Cm(2)
        section.left_margin = Cm(2)
        section.right_margin = Cm(2)
    style = doc.styles["Normal"]
    style.font.name = font
    style.font.size = Pt(size)
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), font)
    pf = style.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = spacing
    pf.first_line_indent = Cm(first_line)
    pf.space_after = Pt(space_after)
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def para(doc, text="", size=14, bold=False, italic=False, align="justify",
         indent=1.25, space_before=0, space_after=0, font="Times New Roman",
         spacing=1.5, color=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.first_line_indent = Cm(indent)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = spacing
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.alignment = {
        "justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "left": WD_ALIGN_PARAGRAPH.LEFT,
        "right": WD_ALIGN_PARAGRAPH.RIGHT,
    }[align]
    if text:
        run = p.add_run(text)
        set_font(run, font, size, bold, italic, color)
    return p


def heading(doc, text, size=16, align="left", space_before=6, space_after=6,
            color=DARK):
    p = para(doc, text, size=size, bold=True, align=align, indent=0,
             space_before=space_before, space_after=space_after, spacing=1.5,
             color=color)
    return p


def page_break(doc):
    doc.add_page_break()


def add_field(paragraph, code):
    run = paragraph.add_run()
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = code
    fld_sep = OxmlElement("w:fldChar")
    fld_sep.set(qn("w:fldCharType"), "separate")
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")
    run._element.append(fld_begin)
    run._element.append(instr)
    run._element.append(fld_sep)
    run._element.append(fld_end)


def add_page_numbers(doc):
    for section in doc.sections:
        p = section.footer.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
        add_field(p, "PAGE")
        for run in p.runs:
            set_font(run, "Times New Roman", 12)


def bullet(doc, text, size=15, level=0, indent_cm=0.75, space_after=4,
           spacing=1.15):
    """Маркированный пункт с крупным шрифтом (через символ «•»)."""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Cm(indent_cm + level * 0.6)
    pf.first_line_indent = Cm(-0.5)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = spacing
    pf.space_after = Pt(space_after)
    pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run("•  " + text)
    set_font(run, "Times New Roman", size)
    return p


